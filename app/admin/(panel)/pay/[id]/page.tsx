import { notFound, redirect } from "next/navigation";
import Logo from "@/components/Logo";
import PrintButton from "@/components/PrintButton";
import { getStaff, kwacha } from "@/lib/admin";
import { SITE } from "@/lib/site";

const monthName = (d: string) => new Date(d + "T00:00:00").toLocaleDateString("en-GB", { month: "long", year: "numeric" });
const day = (iso: string) => new Date(iso).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "Africa/Lusaka" });

export default async function Payslip({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const staff = await getStaff();
  if (!staff) redirect("/admin/login");
  // The database only returns this if it's yours and paid, or if you're management.
  const { data: p } = await staff.supabase.from("payslips").select("*").eq("id", id).maybeSingle();
  if (!p || p.status !== "paid") notFound();
  const [{ data: person }, { data: settings }] = await Promise.all([
    staff.supabase.from("staff").select("full_name,email,is_management,is_lecturer").eq("user_id", p.staff_id).maybeSingle(),
    staff.supabase.from("staff_pay").select("pay_to").eq("user_id", p.staff_id).maybeSingle(),
  ]);
  const role = [person?.is_management && "Management", person?.is_lecturer && "Lecturer"].filter(Boolean).join(" · ");

  return (
    <div className="payslip-wrap">
      <div className="noprint" style={{ display: "flex", justifyContent: "flex-end", marginBottom: 16 }}><PrintButton /></div>
      <article className="payslip">
        <header>
          <div style={{ display: "flex", gap: 12, alignItems: "center" }}>
            <Logo size={56} />
            <div><b className="ps-name">{SITE.name}</b><small>{SITE.address}</small></div>
          </div>
          <div className="ps-title"><span>Payslip</span><b>{monthName(p.period)}</b></div>
        </header>
        <div className="ps-grid">
          <div><span>Employee</span><b>{person?.full_name ?? "Staff member"}</b></div>
          <div><span>Position</span><b>{role || "Staff"}</b></div>
          <div><span>Date paid</span><b>{p.paid_at ? day(p.paid_at) : "–"}</b></div>
          <div><span>Paid by</span><b>{p.method}{settings?.pay_to ? ` · ${settings.pay_to}` : ""}</b></div>
          {p.reference && <div><span>Reference</span><b>{p.reference}</b></div>}
        </div>
        <table className="ps-table">
          <tbody>
            <tr><td>Basic salary</td><td className="num">{kwacha(p.basic)}</td></tr>
            <tr><td>Allowances</td><td className="num">{kwacha(p.allowances)}</td></tr>
            <tr><td>NAPSA</td><td className="num">− {kwacha(p.napsa)}</td></tr>
            <tr><td>NHIMA</td><td className="num">− {kwacha(p.nhima)}</td></tr>
            <tr><td>PAYE</td><td className="num">− {kwacha(p.paye)}</td></tr>
            <tr><td>Other deductions</td><td className="num">− {kwacha(p.deductions)}</td></tr>
            <tr className="net"><td>Net pay</td><td className="num">{kwacha(p.net_pay)}</td></tr>
          </tbody>
        </table>
        {p.note && <p className="ps-note">{p.note}</p>}
        <footer>Status: <b style={{ color: "var(--ok)" }}>Disbursed</b> · Generated by the Manchilui staff portal</footer>
      </article>
    </div>
  );
}
